export const MAP_WIDTH = 360;
export const MAP_HEIGHT = 180;
export const MAP_VIEWBOX = `0 0 ${MAP_WIDTH} ${MAP_HEIGHT}`;

export const LAT_MAX = 85;
export const LAT_MIN = -85;

export interface MapPoint {
  x: number;
  y: number;
}

export interface MapRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface LandmassPath {
  id: string;
  name: string;
  d: string;
  isAntarctica?: boolean;
}

export const GRATICULE_LATITUDES = [-60, -30, 0, 30, 60] as const;
export const GRATICULE_LONGITUDES = [-150, -120, -90, -60, -30, 0, 30, 60, 90, 120, 150] as const;

function clamp(val: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, val));
}

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

/**
 * Equirectangular projection mapping geographic coordinates to SVG viewport space.
 * (0°N, 0°E) maps exactly to the center (180, 90).
 */
export function projectLatLon(lat: number, lon: number): MapPoint {
  const clampedLat = clamp(lat, LAT_MIN, LAT_MAX);
  const clampedLon = clamp(lon, -180, 180);
  const x = ((clampedLon + 180) / 360) * MAP_WIDTH;
  const y = ((LAT_MAX - clampedLat) / (LAT_MAX - LAT_MIN)) * MAP_HEIGHT;
  return { x: round2(x), y: round2(y) };
}

/**
 * Inverse equirectangular projection mapping SVG viewport coordinates back to lat/lon.
 */
export function unprojectXY(x: number, y: number): { lat: number; lon: number } {
  const clampedX = clamp(x, 0, MAP_WIDTH);
  const clampedY = clamp(y, 0, MAP_HEIGHT);
  const lon = (clampedX / MAP_WIDTH) * 360 - 180;
  const lat = LAT_MAX - (clampedY / MAP_HEIGHT) * (LAT_MAX - LAT_MIN);
  return {
    lat: clamp(Math.round(lat * 10000) / 10000, LAT_MIN, LAT_MAX),
    lon: clamp(Math.round(lon * 10000) / 10000, -180, 180),
  };
}

/**
 * Projects a geographic bounding box (e.g. a geohash cell) to an SVG rectangle.
 */
export function projectBoundsToRect(
  minLat: number,
  maxLat: number,
  minLon: number,
  maxLon: number,
): MapRect {
  const topLeft = projectLatLon(maxLat, minLon);
  const bottomRight = projectLatLon(minLat, maxLon);
  return {
    x: topLeft.x,
    y: topLeft.y,
    width: Math.max(0.5, round2(bottomRight.x - topLeft.x)),
    height: Math.max(0.5, round2(bottomRight.y - topLeft.y)),
  };
}

export function formatCoordPair(lat: number, lon: number): string {
  const ns = lat >= 0 ? 'N' : 'S';
  const ew = lon >= 0 ? 'E' : 'W';
  return `${Math.abs(lat).toFixed(2)}°${ns} ${Math.abs(lon).toFixed(2)}°${ew}`;
}

type LonLat = readonly [lon: number, lat: number];

interface RawLandmass {
  id: string;
  name: string;
  isAntarctica?: boolean;
  rings: readonly (readonly LonLat[])[];
}

function ringsToSvgPath(rings: readonly (readonly LonLat[])[]): string {
  return rings
    .map((ring) => {
      if (ring.length === 0) return '';
      const commands = ring.map(([lon, lat], index) => {
        const { x, y } = projectLatLon(lat, lon);
        return `${index === 0 ? 'M' : 'L'}${x} ${y}`;
      });
      return `${commands.join(' ')} Z`;
    })
    .filter(Boolean)
    .join(' ');
}

