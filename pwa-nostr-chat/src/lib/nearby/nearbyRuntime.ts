import type { Event as NostrEvent, EventTemplate } from 'nostr-tools'
import { createGatewayPolicy, isGatewayGeohash, type GatewayCarrier } from './gatewayPolicy.ts'
import { createMeshSession, type NearbyMessage } from './meshSession.ts'
import { cleanNickname, createMeshIdentity, encodeText, hex, MAX_TEXT_BYTES, proofId, type MeshPacket } from './meshWire.ts'
import { Nearby, sendOnLink, unpackNearbyFrame, type NearbyState, type NearbyPlugin } from './nativeNearby.ts'

export type NearbyPeer = { id: string; name: string; gateway: boolean; heard: number }
export type NearbySnapshot = {
  supported: boolean
  active: boolean
  sharing: boolean
  working: boolean
  links: number
  localId: string | null
  peers: NearbyPeer[]
  messages: NearbyMessage[]
  error?: string
}

export const emptyNearby: NearbySnapshot = {
  supported: false, active: false, sharing: false, working: false, links: 0, localId: null, peers: [], messages: [],
}

export interface NearbyPorts {
  selectedGeohash: () => string
  canBridge?: () => boolean
  publish: (event: NostrEvent, geohash: string) => Promise<boolean>
  receive: (event: NostrEvent, geohash: string) => void
  snapshot: (state: NearbySnapshot) => void
}

export interface NearbyRuntime {
  start(nickname: string, options?: { managed?: boolean; requestPermission?: boolean }): Promise<void>
  resume(nickname: string, enabled: () => boolean): Promise<void>
  stop(): Promise<void>
  share(enabled: boolean): void
  sendMesh(text: string): Promise<boolean>
  hasGateway(): boolean
  offlineEvent(template: EventTemplate, geohash: string): NostrEvent | null
  sendThroughGateway(event: NostrEvent, geohash: string): Promise<boolean>
  relayEvent(event: NostrEvent, geohash: string): void
  close(): void
}

type Running = {
  identity: ReturnType<typeof createMeshIdentity>
  session: ReturnType<typeof createMeshSession>
  name: string
  managed: boolean
}

export function makeNearbyRuntime(ports: NearbyPorts, transport: NearbyPlugin = Nearby): NearbyRuntime {
  const policy = createGatewayPolicy()
  let state: NearbySnapshot = emptyNearby
  let radio: NearbyState = { active: false, links: [] }
  let run: Running | null = null
  let closed = false
  const deposits = new Map<string, { event: NostrEvent; geohash: string; sender: string; tries: number; running: boolean }>()

  function publish(patch: Partial<NearbySnapshot> = {}) {
    state = { ...state, peers: run?.session.peers() ?? [], ...patch }
    if (!closed) ports.snapshot(state)
  }

  function canServeGateway() { return state.sharing && (ports.canBridge?.() ?? true) }

  function announce() { return run?.identity.announce(undefined, canServeGateway()) }

  function multicast(packet: MeshPacket, except?: string) {
    return Promise.all(radio.links.filter(link => link.id !== except).map(link => sendOnLink(transport, link, packet)))
      .then(results => results.some(Boolean))
  }

  function flushDeposits(current: Running, only?: string) {
    if (closed || run !== current || !canServeGateway()) return
    let started = 0
    for (const deposit of deposits.values()) {
      if (deposit.running || (only && only !== deposit.event.id)) continue
      if (deposit.tries >= 3 || Math.abs(Date.now() / 1000 - deposit.event.created_at) > 900) {
        deposits.delete(deposit.event.id)
        continue
      }
      if (++started > 3) break
      deposit.running = true
      deposit.tries++
      // Only publish to the gateway's own configured relay directory.
      void ports.publish(deposit.event, deposit.geohash).then(ok => {
        if (!ok || deposits.get(deposit.event.id) !== deposit) return
        deposits.delete(deposit.event.id)
        if (run === current && state.sharing && ports.selectedGeohash() === deposit.geohash) {
          ports.receive(deposit.event, deposit.geohash)
        }
      }).catch(() => {}).finally(() => { deposit.running = false })
    }
  }

  function acceptCarrier(carrier: GatewayCarrier, packet: MeshPacket, ingress: string, current: Running) {
    const sender = hex(packet.sender)
    if (carrier.direction === 'toGateway') {
      if (packet.recipient && hex(packet.recipient) !== current.identity.id) {
        // The wire/session layer already verified the directed envelope. No relay
        // traffic can be generated by passing it onward on BLE.
        if (packet.ttl >= 2 && policy.acceptTransit(carrier, sender)) void multicast({ ...packet, ttl: packet.ttl - 1 }, ingress)
        return
      }
      const accepted = policy.acceptUplink(carrier, sender, canServeGateway())
      if (!accepted) return
      if (deposits.size >= 20 || Array.from(deposits.values()).filter(d => d.sender === sender).length >= 5) return
      const deposit = { event: accepted, geohash: carrier.geohash, sender, tries: 0, running: false }
      deposits.set(accepted.id, deposit)
      // Send immediately. A temporarily unreachable relay can retry on the next radio heartbeat.
      flushDeposits(current, accepted.id)
      return
    }
    const accepted = policy.acceptDownlink(carrier, ports.selectedGeohash())
    if (!accepted) return
    if (accepted.show) ports.receive(accepted.event, carrier.geohash)
    if (packet.ttl >= 2) void multicast({ ...packet, ttl: packet.ttl - 1 }, ingress)
  }

  const listeners = Promise.all([
    transport.addListener('state', incoming => {
      if (closed) return
      const previous = radio
      radio = incoming
      if (!incoming.active) {
        run?.identity.erase()
        run?.session.clear()
        run = null
        policy.reset()
        deposits.clear()
        publish({ active: false, sharing: false, localId: null, links: 0, error: incoming.error })
        return
      }
      if (!run) return
      publish({ active: true, sharing: !!run && (run.managed || state.sharing), links: radio.links.length, error: incoming.error })
      const added = radio.links.filter(link => !previous.links.some(prior => prior.id === link.id))
      const intro = added.length ? announce() : null
      if (intro) for (const link of added) void sendOnLink(transport, link, intro)
    }),
    transport.addListener('frame', incoming => {
      const current = run
      if (closed || !current || !radio.active) return
      const wire = unpackNearbyFrame(incoming.wire)
      if (!wire) return
      const obs = current.session.receive(wire, incoming.link)
      if (!obs.length) return
      const messages = obs.flatMap(o => o.message ? [o.message] : [])
      publish(messages.length ? { messages: [...state.messages, ...messages].slice(-160) } : {})
      for (const o of obs) {
        if (o.carrier) acceptCarrier(o.carrier, o.relay, o.ingress, current)
        else if (o.relay.ttl >= 2) void multicast({ ...o.relay, ttl: o.relay.ttl - 1 }, o.ingress)
      }
    }),
  ])
  void listeners.then(() => transport.capabilities()).then(r => publish({ supported: r.supported })).catch(() => {})
  const timer = globalThis.setInterval(() => {
    if (!run || !radio.active) return
    publish()
    flushDeposits(run)
    const packet = announce()
    if (packet && radio.links.length) void multicast(packet)
  }, 15_000)

  async function start(nickname: string, { managed = false, requestPermission = true } = {}) {
    if (closed || state.working || radio.active || !state.supported) return
    publish({ working: true, error: undefined, ...(managed ? {} : { messages: [] }) })
    const name = cleanNickname(nickname)
    const identity = createMeshIdentity(name)
    const current = { name, identity, session: createMeshSession(identity.id), managed }
    run = current
    publish({ localId: identity.id })
    try {
      await transport.start({ requestPermission })
      // Android orders cancellation in the native plugin, including pending permissions.
      // A delayed start from an obsolete runtime must not stop a newer Android runtime.
      if (!managed && (closed || run !== current)) await transport.stop()
    } catch (error) {
      if (run === current) {
        current.identity.erase()
        run = null
        publish({ localId: null, error: error instanceof Error ? error.message : 'Bluetooth could not start.' })
      }
    } finally { publish({ working: false }) }
  }

  let probing = false
  return {
    start,
    async resume(nickname, enabled) {
      if (probing || closed || state.working || radio.active || !enabled()) return
      probing = true
      try {
        const caps = await transport.capabilities()
        if (closed || state.working || radio.active || !enabled()) return
        if (state.supported !== caps.supported || state.error !== caps.error) {
          publish({ supported: caps.supported, error: caps.error })
        }
        if (caps.ready) await start(nickname, { managed: true, requestPermission: false })
      } catch { /* Native bridge may not be ready yet; recheck on the next foreground tick. */ }
      finally { probing = false }
    },
    async stop() {
      run?.identity.erase()
      run?.session.clear()
      run = null
      deposits.clear()
      policy.reset()
      publish({ active: false, sharing: false, links: 0, localId: null, error: undefined })
      try { await transport.stop() } catch {
        publish({ error: 'Could not stop Bluetooth.' })
      }
    },
    share(enabled) {
      if (!radio.active || !run || run.managed) return
      if (!enabled) deposits.clear()
      publish({ sharing: enabled })
      const packet = announce()
      if (packet) void multicast(packet)
    },
    async sendMesh(text) {
      const content = text.trim()
      const current = run
      if (!current || !radio.active || !radio.links.length || !content || encodeText(content).length > MAX_TEXT_BYTES) return false
      const intro = announce()!
      const packet = current.identity.text(content)
      const accepted = await Promise.all(radio.links.map(link => sendOnLink(transport, link, intro, packet)))
      if (run !== current || !accepted.some(Boolean)) return false
      publish({ messages: [...state.messages, {
        id: proofId(packet), name: current.name, sender: current.identity.id, when: packet.when, body: content,
        local: true, status: 'queued' as const,
      }].slice(-160) })
      return true
    },
    hasGateway: () => Boolean(radio.active && radio.links.length && run?.session.peers().some(peer => peer.gateway)),
    offlineEvent: (template, geohash) => policy.signOffline(template, geohash),
    async sendThroughGateway(event, geohash) {
      const gateway = run?.session.peers().filter(peer => peer.gateway).sort((a, b) => b.heard - a.heard)[0]
      if (!run || !gateway) return false
      const carrier = policy.localPacket(event, geohash)
      const packet = carrier ? run.identity.carrier(carrier, gateway.id) : null
      const intro = announce()
      if (!packet || !intro) return false
      const results = await Promise.all(radio.links.map(link => sendOnLink(transport, link, intro, packet)))
      return results.some(Boolean)
    },
    relayEvent(event, geohash) {
      if (!run || !radio.active || !radio.links.length || !isGatewayGeohash(geohash)) return
      const carrier = policy.relayPacket(event, geohash, canServeGateway())
      const packet = carrier ? run.identity.carrier(carrier) : null
      if (packet) void multicast(packet)
    },
    close() {
      closed = true
      globalThis.clearInterval(timer)
      run?.identity.erase()
      run?.session.clear()
      run = null
      policy.reset()
      deposits.clear()
      void listeners.then(handles => Promise.all(handles.map(h => h.remove()))).catch(() => {})
      void transport.stop().catch(() => {})
    },
  }
}
